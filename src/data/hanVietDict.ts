export function getKanjiMeaning(kanji: string): string {
  if (!kanji) return "";
  const cleaned = kanji.trim();
  if (KANJI_MEANING_DICT[cleaned]) {
    return KANJI_MEANING_DICT[cleaned];
  }

  // Fallback: lookup each Kanji character meaning
  const meanings: string[] = [];
  for (const char of cleaned) {
    if (KANJI_MEANING_DICT[char]) {
      meanings.push(KANJI_MEANING_DICT[char]);
    }
  }
  return meanings.length > 0 ? meanings.join("; ") : "";
}

/**
 * Returns the Han-Viet representation for a given Kanji string.
 * First checks direct match, then builds from individual Kanji characters if needed.
 */
export function getHanViet(kanji: string): string {
  if (!kanji) return "";
  const cleaned = kanji.trim();
  if (HAN_VIET_DICT[cleaned]) {
    return HAN_VIET_DICT[cleaned];
  }

  // Fallback: lookup each Kanji character
  const parts: string[] = [];
  for (const char of cleaned) {
    if (HAN_VIET_DICT[char]) {
      parts.push(HAN_VIET_DICT[char]);
    }
  }
  return parts.length > 0 ? parts.join(" ") : cleaned;
}
