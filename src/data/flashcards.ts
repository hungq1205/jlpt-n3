export type FlashcardType = 'vocab' | 'kanji';

export interface KanjiVocabItem {
  kanji: string;
  kana: string;
  hanViet: string;
  meaning: string;
}

export interface Flashcard {
  id: number;
  type?: FlashcardType; // 'vocab' (default) or 'kanji'
  kanji: string;
  kana: string;
  viet: string;
  vietnamese?: string;
  hanViet: string;
  partOfSpeech?: string;

  // Specific to kanji card:
  onyomi?: string;
  kunyomi?: string;
  kanjiMeaning?: string;
  vocabList?: KanjiVocabItem[];

  // Examples
  example: string;
  exampleRuby?: string;
  exampleKana?: string;
  exampleViet: string;
}

export interface Lesson {
  id: string;
  title: string;
  description: string;
  level: string;
  cards: Flashcard[];
}

